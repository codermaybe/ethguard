#!/usr/bin/env bash
# Build pre-tag release assets and verify them before optional success-only cleanup.
# Requires Bash 4+, sha256sum, and (for builds) GoReleaser OSS v2.20.0 on Linux amd64.
set -euo pipefail

readonly goreleaser_version='2.20.0'
repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
readonly repo_root
cd -- "${repo_root}"

fail() {
    echo "release_build: $*" >&2
    exit 1
}

usage() {
    echo 'usage: bash scripts/release_build.sh [--keep-artifacts | --verify-artifacts]'
}

mode=build
case "${1:-}" in
    '') ;;
    --keep-artifacts) mode=keep ;;
    --verify-artifacts) mode=verify ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
esac
if [ "$#" -gt 1 ]; then
    usage >&2
    exit 2
fi
if [ "${BASH_VERSINFO[0]}" -lt 4 ]; then
    fail 'Bash 4 or newer is required'
fi
command -v sha256sum >/dev/null 2>&1 || fail 'sha256sum is required'

readonly commands=(soak rpcsample shapeprobe specbundle specdiff specsync)
readonly platforms=(linux_amd64 linux_arm64 darwin_arm64)
readonly expected_binary_count=$((${#commands[@]} * ${#platforms[@]}))

verify_artifacts() {
    local cmd platform name line
    local count=0
    local checksum_line='^[0-9a-f]{64}  ([a-z0-9_]+)$'
    local -A expected=() seen=()

    [ -d dist ] && [ ! -L dist ] || fail 'dist must be a real directory'
    [ -f dist/checksums.sha256 ] && [ ! -L dist/checksums.sha256 ] ||
        fail 'dist/checksums.sha256 must be a regular, non-symlink file'
    for cmd in "${commands[@]}"; do
        for platform in "${platforms[@]}"; do
            name="${cmd}_${platform}"
            expected["${name}"]=1
            [ -f "dist/${name}" ] && [ ! -L "dist/${name}" ] ||
                fail "missing regular, non-symlink binary: dist/${name}"
        done
    done

    # Validate membership before asking sha256sum to open any manifest paths.
    # Exactly two spaces is the format generated by this pinned GoReleaser.
    while IFS= read -r line || [ -n "${line}" ]; do
        [[ "${line}" =~ ${checksum_line} ]] || fail 'malformed checksum manifest line'
        name="${BASH_REMATCH[1]}"
        [ -n "${expected[${name}]:-}" ] || fail "unexpected checksum entry: ${name}"
        [ -z "${seen[${name}]:-}" ] || fail "duplicate checksum entry: ${name}"
        seen["${name}"]=1
        count=$((count + 1))
    done < dist/checksums.sha256
    [ "${count}" -eq "${expected_binary_count}" ] || fail "expected ${expected_binary_count} checksum entries, found ${count}"
    (cd dist && sha256sum --check --strict checksums.sha256)
}

# The protected publish job uses this read-only path after downloading assets.
# It neither requires build tools nor executes downloaded binaries.
if [ "${mode}" = verify ]; then
    verify_artifacts
    echo "release artifacts verified (${expected_binary_count} binaries); files left unchanged"
    exit 0
fi

# Never use --clean: an existing path may contain artifacts owned by the caller.
if [ -e dist ] || [ -L dist ]; then
    fail 'dist already exists; inspect and move/remove it explicitly before building'
fi
[ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ] ||
    fail "build verification requires a Linux amd64 host to execute all ${#commands[@]} -h smoke checks"
command -v goreleaser >/dev/null 2>&1 ||
    fail "install GoReleaser OSS v${goreleaser_version} and put it on PATH"
installed_version="$(goreleaser --version)"
version_match='(^|[[:space:]])GitVersion:[[:space:]]+v?([^[:space:]]+)'
if [[ ! "${installed_version}" =~ ${version_match} ]] ||
    [ "${BASH_REMATCH[2]}" != "${goreleaser_version}" ]; then
    fail "requires GoReleaser OSS v${goreleaser_version}; installed tool reports: ${installed_version}"
fi

retain_failure() {
    local status="$?"
    if [ "${status}" -ne 0 ] && { [ -e dist ] || [ -L dist ]; }; then
        echo 'release_build: failed; dist retained for diagnosis (no Go caches were removed)' >&2
    fi
}
trap retain_failure EXIT

echo "==> checking GoReleaser v${goreleaser_version} configuration"
goreleaser check --config .goreleaser.yaml
echo '==> building pre-tag snapshot assets (no publishing or tag creation)'
goreleaser release --config .goreleaser.yaml --snapshot

# GoReleaser's binary archive changes asset names, not their on-disk paths.
# Hard-link the fixed targets into the payload root; retain metadata paths and
# avoid copying binaries or depending on the default architecture variant suffix.
for cmd in "${commands[@]}"; do
    for platform in "${platforms[@]}"; do
        candidates=(dist/"${cmd}_${platform}"_*/"${cmd}")
        [ "${#candidates[@]}" -eq 1 ] && [ -f "${candidates[0]}" ] && [ ! -L "${candidates[0]}" ] ||
            fail "expected one isolated build for ${cmd}_${platform}"
        ln -- "${candidates[0]}" "dist/${cmd}_${platform}"
    done
done

echo '==> verifying exact binary membership and SHA-256 checksums'
verify_artifacts
echo '==> smoke checking Linux amd64 help entrypoints'
for cmd in "${commands[@]}"; do
    [ -x "dist/${cmd}_linux_amd64" ] || fail "binary is not executable: ${cmd}_linux_amd64"
    "./dist/${cmd}_linux_amd64" -h
done
# Detect even accidental mutation during execution before archiving or cleanup.
verify_artifacts

if [ "${mode}" = keep ]; then
    echo 'release build and smoke checks passed; verified assets retained in dist'
else
    rm -r -- "${repo_root}/dist"
    echo 'release build and smoke checks passed; generated dist removed (Go caches untouched)'
fi
