package main

// Schema semantics are resolved by walk. This file renders that model with
// Jennifer; it neither changes schemas nor interprets them at runtime.
import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/dave/jennifer/jen"
)

const specPackage = "github.com/codermaybe/ethguard/internal/spec"
const codecPackage = "github.com/codermaybe/ethguard/internal/ethcodec"

type genReport struct {
	nameCollisions                                []collision
	visited                                       map[string]bool
	methods                                       []string
	errata                                        []string
	objects, countFields, countUnions, countShims int
}

func emit(reg *registry, version string, roots map[string]*ref, outPath string) error {
	reg.report.countUnions = len(reg.unionList)
	reg.report.countShims = 0
	for method, r := range roots {
		if !rootUsesConstructor(method, r) {
			reg.report.countShims++
		}
	}
	f := jen.NewFilePathName("github.com/codermaybe/ethguard/ethapi", "ethapi")
	f.HeaderComment(fmt.Sprintf("Code generated by rpc/internal/wire/gen from execution-apis %s; DO NOT EDIT.", version))
	for _, applied := range reg.report.errata {
		f.HeaderComment("Reviewed schema erratum: " + applied)
	}
	f.HeaderComment("Typed official values preserve constraints, declared composition kind and nullable presence.")
	f.HeaderComment("Constructors enforce schema constraints. Directly constructed typed values must preserve those invariants;")
	f.HeaderComment("marshaling encodes once without revalidation, except for union member selection checks.")
	f.HeaderComment(fmt.Sprintf("Built from %d methods: %d object types, %d fields, %d unions, %d result shims.",
		len(reg.report.methods), reg.report.objects, reg.report.countFields, reg.report.countUnions, reg.report.countShims))
	f.Const().Id("generatedBundleVersion").Op("=").Lit(version)
	f.Func().Id("init").Params().Block(
		jen.If(jen.Id("v").Op(":=").Qual(specPackage, "Version").Call(),
			jen.Id("v").Op("!=").Id("generatedBundleVersion")).Block(
			jen.Panic(jen.Qual("fmt", "Sprintf").Call(
				jen.Lit("wire: generated spec %q != pin %q"), jen.Id("generatedBundleVersion"), jen.Id("v"))),
		),
	)
	for _, n := range natives {
		emitNative(f, n)
	}
	for _, r := range reg.values {
		emitValue(f, r)
	}
	for _, obj := range reg.objects {
		emitObject(f, obj)
	}
	for _, u := range reg.unionList {
		emitUnion(f, u)
	}
	methods := make([]string, 0, len(roots))
	for method := range roots {
		methods = append(methods, method)
	}
	sort.Strings(methods)
	for _, method := range methods {
		r := roots[method]
		if rootUsesConstructor(method, r) {
			continue
		}
		f.Commentf("%s parses the complete official %s result.", methodShimName(method), method)
		f.Func().Id(methodShimName(method)).Params(rawParameter()).Params(typeCode(r), jen.Error()).Block(
			jen.Return(jen.Id(r.parser).Call(jen.Id("raw"))),
		)
	}
	if err := f.Save(outPath); err != nil {
		return fmt.Errorf("emit: %w", err)
	}
	return nil
}

func rootUsesConstructor(method string, r *ref) bool {
	return !r.pointer && (r.kind == refObject || r.kind == refUnion) && methodShimName(method) == "New"+r.typeName
}

func rawParameter() *jen.Statement {
	return jen.Id("raw").Qual("encoding/json", "RawMessage")
}

func errorf(message string, args ...jen.Code) *jen.Statement {
	return jen.Qual("fmt", "Errorf").Call(append([]jen.Code{jen.Lit(message)}, args...)...)
}

func typeCode(r *ref) *jen.Statement {
	var code *jen.Statement
	if r.kind == refArray {
		code = jen.Index().Add(typeCode(r.elem))
	} else if r.kind == refScalar {
		code = jen.Id(r.native)
	} else {
		code = jen.Id(r.typeName)
	}
	if r.pointer {
		return jen.Op("*").Add(code)
	}
	return code
}

func emitNative(f *jen.File, n nativeDescriptor) {
	f.Commentf("%s is the %s.", n.name, n.doc)
	f.Type().Id(n.name).String()
	pattern := "native" + n.name + "Pattern"
	if n.pattern != "" {
		f.Var().Id(pattern).Op("=").Qual("regexp", "MustCompile").Call(jen.Lit(n.pattern))
	}
	f.Func().Id("New"+n.name).Params(rawParameter()).Params(jen.Id(n.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(
			jen.Return(jen.Lit(""), errorf(n.name+": expected a non-null value")),
		)
		if n.parse.fn != "" {
			args := []jen.Code{jen.Id("raw")}
			for _, arg := range n.parse.extraArgs {
				args = append(args, jen.Lit(arg))
			}
			g.List(jen.Id("text"), jen.Err()).Op(":=").Qual(codecPackage, n.parse.fn).Call(args...)
			g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Lit(""), jen.Err()))
			if n.parse.number {
				g.Return(jen.Id(n.name).Call(jen.Id("text").Dot("String").Call()), jen.Nil())
				return
			}
		} else {
			g.Var().Id("text").String()
			g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("text")), jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Lit(""), errorf("expected string: %w", jen.Err())),
			)
		}
		if n.pattern != "" {
			message := n.name + ": invalid spelling %q"
			if n.parse.fn != "" {
				message = n.name + ": canonical spelling %q does not match official pattern"
			}
			g.If(jen.Op("!").Id(pattern).Dot("MatchString").Call(jen.Id("text"))).Block(
				jen.Return(jen.Lit(""), errorf(message, jen.Id("text"))),
			)
		}
		g.Return(jen.Id(n.name).Call(jen.Id("text")), jen.Nil())
	})
	f.Func().Params(jen.Id("v").Id(n.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).BlockFunc(func(g *jen.Group) {
		if n.parse.number {
			g.Return(jen.Index().Byte().Call(jen.Id("v")), jen.Nil())
		} else {
			g.Return(jen.Qual(codecPackage, "MarshalNoEscape").Call(jen.String().Call(jen.Id("v"))))
		}
	})
}

func emitValue(f *jen.File, r *ref) {
	pattern := r.pattern
	if nativeForPattern(pattern) == r.native {
		pattern = ""
	}
	if pattern != "" {
		f.Var().Id(r.parser+"Pattern").Op("=").Qual("regexp", "MustCompile").Call(jen.Lit(pattern))
	}
	f.Func().Id(r.parser).Params(rawParameter()).Params(typeCode(r), jen.Error()).BlockFunc(func(g *jen.Group) {
		if r.pointer {
			g.If(jen.Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(jen.Return(jen.Nil(), jen.Nil()))
			g.List(jen.Id("value"), jen.Err()).Op(":=").Id(r.inner.parser).Call(jen.Id("raw"))
			g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Nil(), jen.Err()))
			g.Return(jen.Op("&").Id("value"), jen.Nil())
			return
		}
		g.Var().Id("out").Add(typeCode(r))
		if r.kind != refUnion {
			g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(
				jen.Return(jen.Id("out"), errorf(r.path+": expected a non-null value")),
			)
		}
		switch r.kind {
		case refScalar:
			if r.native == "bool" || r.native == "int" {
				g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("out")), jen.Err().Op("!=").Nil()).Block(
					jen.Return(jen.Id("out"), errorf(r.path+": %w", jen.Err())),
				)
			} else {
				g.List(jen.Id("value"), jen.Err()).Op(":=").Id("New" + r.native).Call(jen.Id("raw"))
				g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(r.path+": %w", jen.Err())))
				g.Id("out").Op("=").Id("value")
			}
		case refObject, refUnion:
			g.List(jen.Id("value"), jen.Err()).Op(":=").Id("New" + r.typeName).Call(jen.Id("raw"))
			g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), jen.Err()))
			g.Id("out").Op("=").Id("value")
		case refArray:
			g.Var().Id("rows").Index().Qual("encoding/json", "RawMessage")
			g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("rows")), jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Id("out"), errorf(r.path+": expected array: %w", jen.Err())),
			)
			g.Id("out").Op("=").Make(typeCode(r), jen.Len(jen.Id("rows")))
			g.For(jen.List(jen.Id("i"), jen.Id("row")).Op(":=").Range().Id("rows")).Block(
				jen.List(jen.Id("value"), jen.Err()).Op(":=").Id(r.elem.parser).Call(jen.Id("row")),
				jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(r.path+"[%d]: %w", jen.Id("i"), jen.Err()))),
				jen.Id("out").Index(jen.Id("i")).Op("=").Id("value"),
			)
		}
		if r.hasConst {
			var condition *jen.Statement
			if r.native == "Number" {
				condition = compareNumber(fmt.Sprint(r.constant)).Op("!=").Lit(0)
			} else {
				condition = jen.Id("out").Op("!=").Add(constCode(r.constant))
			}
			g.If(condition).Block(jen.Return(jen.Id("out"), errorf(r.path+": expected constant")))
		}
		if pattern != "" {
			g.If(jen.Op("!").Id(r.parser + "Pattern").Dot("MatchString").Call(jen.String().Call(jen.Id("out")))).Block(
				jen.Return(jen.Id("out"), errorf(r.path+": does not match official pattern")),
			)
		}
		if r.minimum != nil {
			g.If(compareNumber(r.minimum.String()).Op("<").Lit(0)).Block(jen.Return(jen.Id("out"), errorf(r.path+": below official minimum")))
		}
		if r.maximum != nil {
			g.If(compareNumber(r.maximum.String()).Op(">").Lit(0)).Block(jen.Return(jen.Id("out"), errorf(r.path+": above official maximum")))
		}
		g.Return(jen.Id("out"), jen.Nil())
	})
}

func compareNumber(value string) *jen.Statement {
	return jen.Qual(codecPackage, "CompareNumbers").Call(
		jen.Qual("encoding/json", "Number").Call(jen.Id("out")),
		jen.Qual("encoding/json", "Number").Call(jen.Lit(value)),
	)
}

func constCode(value any) *jen.Statement {
	if number, ok := value.(json.Number); ok {
		// Non-integer numeric constants are compared as exact Number values.
		// The walker has already checked the integer range for int constants.
		integer, err := strconv.ParseInt(number.String(), 10, 64)
		if err != nil {
			panic(fmt.Sprintf("emit: invalid integer constant %q: %v", number, err))
		}
		return jen.Lit(int(integer))
	}
	return jen.Lit(value)
}

func fieldTypeCode(f fieldModel) *jen.Statement {
	if !f.req {
		return jen.Op("*").Add(typeCode(f.ref))
	}
	return typeCode(f.ref)
}

func fieldTag(f fieldModel) string {
	if !f.req {
		return f.json + ",omitempty"
	}
	return f.json
}

func emitFields(g *jen.Group, obj *objectModel) {
	for _, field := range obj.fields {
		g.Id(field.goName).Add(fieldTypeCode(field)).Tag(map[string]string{"json": fieldTag(field)})
	}
}

func emitObject(f *jen.File, obj *objectModel) {
	f.Commentf("%s is the official execution-apis object; optional nullable fields distinguish absence from null.", obj.name)
	f.Commentf("New%s enforces schema constraints; directly constructed values must preserve those invariants.", obj.name)
	if len(obj.from) > 1 {
		f.Commentf("Shape shared by: %s.", strings.Join(obj.from, ", "))
	}
	f.Type().Id(obj.name).StructFunc(func(g *jen.Group) { emitFields(g, obj) })
	f.Func().Id("New"+obj.name).Params(rawParameter()).Params(jen.Id(obj.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Var().Id("out").Id(obj.name)
		g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(
			jen.Return(jen.Id("out"), errorf(obj.name+": expected a non-null object")),
		)
		g.Var().Id("fields").StructFunc(func(fields *jen.Group) {
			for _, field := range obj.fields {
				fields.Id(field.goName).Qual("encoding/json", "RawMessage").Tag(map[string]string{"json": field.json})
			}
		})
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("fields")), jen.Err().Op("!=").Nil()).Block(
			jen.Return(jen.Id("out"), errorf(obj.name+": expected object: %w", jen.Err())),
		)
		for _, field := range obj.fields {
			g.If(jen.Len(jen.Id("fields").Dot(field.goName)).Op("==").Lit(0)).BlockFunc(func(missing *jen.Group) {
				if field.req {
					missing.Return(jen.Id("out"), errorf(obj.name+": missing required field "+field.json))
				}
			}).Else().BlockFunc(func(present *jen.Group) {
				present.List(jen.Id("value"), jen.Err()).Op(":=").Id(field.ref.parser).Call(jen.Id("fields").Dot(field.goName))
				present.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), jen.Err()))
				value := jen.Id("value")
				if !field.req {
					value = jen.Op("&").Id("value")
				}
				present.Id("out").Dot(field.goName).Op("=").Add(value)
			})
		}
		g.Return(jen.Id("out"), jen.Nil())
	})
	values := jen.Dict{}
	for _, field := range obj.fields {
		values[jen.Id(field.goName)] = jen.Id("v").Dot(field.goName)
	}
	f.Func().Params(jen.Id("v").Id(obj.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).Block(
		jen.Return(jen.Qual(codecPackage, "MarshalNoEscape").Call(
			jen.StructFunc(func(g *jen.Group) { emitFields(g, obj) }).Values(values),
		)),
	)
}

func emitUnion(f *jen.File, u *unionModel) {
	f.Commentf("%s retains the official %s branches in declaration order.", u.name, u.kind)
	if u.kind == "anyOf" {
		f.Comment("Multiple matching schemas are valid; the first successful branch is the canonical representation.")
	} else {
		f.Comment("Exactly one complete branch must validate.")
	}
	if len(u.from) > 1 {
		f.Commentf("Shape shared by: %s.", strings.Join(u.from, ", "))
	}
	f.Type().Id(u.name).StructFunc(func(g *jen.Group) {
		for _, b := range u.branches {
			g.Commentf("Official %s[%d]: %s.", u.kind, b.index, b.title)
			g.Id(b.goName).Op("*").Add(typeCode(b.ref)).Tag(map[string]string{"json": "-"})
		}
	})
	f.Func().Id("New"+u.name).Params(rawParameter()).Params(jen.Id(u.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Var().Id("out").Id(u.name)
		g.Id("matches").Op(":=").Lit(0)
		if u.nullable {
			g.If(jen.Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).BlockFunc(func(null *jen.Group) {
				if u.kind == "anyOf" {
					null.Return(jen.Id("out"), jen.Nil())
				} else {
					null.Id("matches").Op("++")
				}
			})
		}
		for _, b := range u.branches {
			g.If(jen.List(jen.Id("value"), jen.Err()).Op(":=").Id(b.ref.parser).Call(jen.Id("raw")), jen.Err().Op("==").Nil()).BlockFunc(func(match *jen.Group) {
				if u.kind == "oneOf" {
					match.Id("matches").Op("++")
				}
				match.Id("out").Dot(b.goName).Op("=").Op("&").Id("value")
				if u.kind == "anyOf" {
					match.Return(jen.Id("out"), jen.Nil())
				}
			})
		}
		g.If(jen.Id("matches").Op("!=").Lit(1)).Block(
			jen.Return(jen.Id(u.name).Values(), errorf(u.name+": expected "+u.kind+" branch match, got %d", jen.Id("matches"))),
		)
		g.Return(jen.Id("out"), jen.Nil())
	})
	f.Func().Params(jen.Id("u").Id(u.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Id("selected").Op(":=").Lit(0)
		for _, b := range u.branches {
			g.If(jen.Id("u").Dot(b.goName).Op("!=").Nil()).Block(jen.Id("selected").Op("++"))
		}
		if u.nullable {
			g.If(jen.Id("selected").Op("==").Lit(0)).Block(jen.Return(jen.Index().Byte().Call(jen.Lit("null")), jen.Nil()))
		}
		g.If(jen.Id("selected").Op("!=").Lit(1)).Block(
			jen.Return(jen.Nil(), errorf(u.name+": expected exactly one selected member, got %d", jen.Id("selected"))),
		)
		for i, b := range u.branches {
			result := jen.Id("u").Dot(b.goName).Dot("MarshalJSON").Call()
			if b.ref.pointer || b.ref.kind == refScalar || b.ref.kind == refArray {
				result = jen.Qual(codecPackage, "MarshalNoEscape").Call(jen.Op("*").Id("u").Dot(b.goName))
			}
			if i < len(u.branches)-1 {
				g.If(jen.Id("u").Dot(b.goName).Op("!=").Nil()).Block(jen.Return(result))
			} else {
				g.Return(result)
			}
		}
	})
}

func methodShimName(method string) string { return "New" + methodCamel(method) + "Result" }
func methodCamel(method string) string {
	trimmed := strings.TrimPrefix(method, "eth_")
	trimmed = strings.TrimPrefix(trimmed, "net_")
	if trimmed == "" {
		trimmed = method
	}
	return strings.ToUpper(trimmed[:1]) + trimmed[1:]
}
