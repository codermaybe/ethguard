package main

// The emitter renders the walked model into one generated Go file with
// jennifer. Wire-contract rules live in model.go and walk.go; this file is
// rendering policy only.

import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/dave/jennifer/jen"
)

// genReport records what the generator built, for the audit comment and CI
// drift checks.
type genReport struct {
	nameCollisions   []collision
	missingOverrides []string
	visited          map[string]bool
	patternVars      map[string]string
	methods          []string
	objects          int
	countFields      int
	countUnions      int
	countShims       int
}

// emit renders the model into the generated Go file and writes it to outPath.
func emit(reg *registry, version string, roots map[string]*ref, outPath string) error {
	f := jen.NewFilePathName("github.com/codermaybe/ethguard/rpc/internal/wire", "wire")
	f.NoFormat = true

	// Version interlock: a types.gen.go from another spec release must fail
	// loudly at init rather than drift silently.
	f.Const().Id("generatedBundleVersion").Op("=").Lit(version)
	f.Func().Id("init").Params().Block(
		jen.If(
			jen.Id("v").Op(":=").
				Qual("github.com/codermaybe/ethguard/internal/spec", "Version").Call(),
			jen.Id("v").Op("!=").Id("generatedBundleVersion"),
		).Block(
			jen.Panic(jen.Qual("fmt", "Sprintf").Call(
				jen.Lit("wire: types.gen.go built for spec %q but the pinned spec is %q"),
				jen.Id("generatedBundleVersion"), jen.Id("v"),
			)),
		),
	)

	// Compiled patterns backing the relaxed official kinds.
	names := make([]string, 0, len(relaxedKinds))
	for name := range relaxedKinds {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, native := range names {
		f.Var().Id(relaxedKinds[native]).Op("=").
			Qual("regexp", "MustCompile").Call(jen.Lit(nativePatternOf(native)))
	}

	emitNatives(f)
	for _, obj := range reg.objects {
		emitObject(f, reg, obj)
	}
	for _, um := range reg.unionList {
		emitUnion(f, um)
	}
	reg.report.countUnions = len(reg.unionList)
	emitRoots(f, reg, roots)
	reg.report.countShims = len(roots)

	// Package header, written last so the counters reflect the emitted model.
	f.PackageComment(generatedPackageComment(version, reg.report))

	// Compiled text-pattern constraint vars. They are discovered during
	// object emission above, so the declarations come after the bodies;
	// top-level declaration order does not matter in Go.
	textPatterns := make([]string, 0, len(reg.report.patternVars))
	for pattern := range reg.report.patternVars {
		textPatterns = append(textPatterns, pattern)
	}
	sort.Strings(textPatterns)
	for _, pattern := range textPatterns {
		f.Var().Id(reg.report.patternVars[pattern]).Op("=").
			Qual("regexp", "MustCompile").Call(jen.Lit(pattern))
	}

	// Audit trail: drifted overrides stay visible in the generated file.
	for path, name := range overrideNameByPath {
		if !reg.report.visited[path] {
			f.Comment(fmt.Sprintf("unused override %q -> %q (path vanished from the pinned bundle)", path, name))
		}
	}

	source, err := format.Source([]byte(f.GoString()))
	if err != nil {
		keep := outPath + ".bak"
		_ = os.WriteFile(keep, []byte(f.GoString()), 0o644)
		return fmt.Errorf("emit: format: %w (raw kept at %s)", err, keep)
	}
	return os.WriteFile(outPath, []byte(source), 0o644)
}

func generatedPackageComment(version string, report *genReport) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Code generated by rpc/internal/wire/gen from execution-apis %s; DO NOT EDIT.\n\n", version)
	b.WriteString("The types here are the execution-apis standard definitions the project\n")
	b.WriteString("consumes instead of go-ethereum dialect types: pattern-validated native\n")
	b.WriteString("scalars, result objects in canonical field order, and tagged unions for\n")
	b.WriteString("official oneOf branches. Every parse routes through this package's\n")
	b.WriteString("hand-written normalizers, so generated and protected encoders admit the\n")
	b.WriteString("same bytes.\n\n")
	fmt.Fprintf(&b, "Built from %d methods: %d object types, %d fields, %d unions, %d result shims.",
		len(report.methods), report.objects, report.countFields, report.countUnions, report.countShims)
	return b.String()
}

// --- native scalars ---

func emitNatives(f *jen.File) {
	names := make([]string, 0, len(nativeDoc))
	for name := range nativeDoc {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		info := nativeParse(name)
		f.Commentf("%s is the %s.", name, nativeDoc[name])
		f.Type().Id(name).String()
		f.Func().Id("New"+name).Params(
			jen.Id("raw").Qual("encoding/json", "RawMessage"),
		).Params(jen.Id(name), jen.Error()).Block(nativeParseBody(name, info)...)

		if name == "Ratio" {
			// Ratio is a JSON number literal, never a quoted string.
			f.Func().Params(jen.Id("v").Id(name)).Id("MarshalJSON").Params().
				Params(jen.Index().Byte(), jen.Error()).Block(
				jen.Return(jen.Index().Byte().Call(jen.Id("v")), jen.Nil()),
			)
			continue
		}
		f.Func().Params(jen.Id("v").Id(name)).Id("MarshalJSON").Params().
			Params(jen.Index().Byte(), jen.Error()).Block(
			// json.RawMessage is assignable to []byte, so the multi-value
			// return type-checks directly.
			jen.Return(jen.Id("MarshalNoEscape").Call(jen.Id("string").Call(jen.Id("v")))),
		)
	}
}

func nativeParseBody(name string, info nativeParseInfo) []jen.Code {
	switch {
	case name == "Text" || (info.fn == "" && info.regex == ""):
		return []jen.Code{
			jen.Var().Id("text").String(),
			jen.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
				Call(jen.Id("raw"), jen.Op("&").Id("text")), jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Lit(""), jen.Qual("fmt", "Errorf").
					Call(jen.Lit("expected a string: %w"), jen.Err())),
			),
			jen.Return(jen.Id(name).Call(jen.Id("text")), jen.Nil()),
		}
	case info.ratio:
		return []jen.Code{
			jen.Id("number").Op(",").Err().Op(":=").Add(nativeCall(info)),
			jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Lit(""), jen.Err())),
			jen.Return(jen.Id(name).Call(jen.Id("number").Dot("String").Call()), jen.Nil()),
		}
	case info.fn != "" && info.regex != "":
		return []jen.Code{
			jen.Id("text").Op(",").Err().Op(":=").Add(nativeCall(info)),
			jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Lit(""), jen.Err())),
			jen.If(jen.Op("!").Id(info.regex).Dot("MatchString").Call(jen.Id("text"))).Block(
				jen.Return(jen.Lit(""), jen.Qual("fmt", "Errorf").
					Call(jen.Lit("invalid spelling %q"), jen.Id("text"))),
			),
			jen.Return(jen.Id(name).Call(jen.Id("text")), jen.Nil()),
		}
	case info.regex != "":
		return []jen.Code{
			jen.Var().Id("text").String(),
			jen.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
				Call(jen.Id("raw"), jen.Op("&").Id("text")), jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Lit(""), jen.Qual("fmt", "Errorf").
					Call(jen.Lit("expected a hex string: %w"), jen.Err())),
			),
			jen.If(jen.Op("!").Id(info.regex).Dot("MatchString").Call(jen.Id("text"))).Block(
				jen.Return(jen.Lit(""), jen.Qual("fmt", "Errorf").
					Call(jen.Lit("invalid spelling %q"), jen.Id("text"))),
			),
			jen.Return(jen.Id(name).Call(jen.Id("text")), jen.Nil()),
		}
	}
	return []jen.Code{
		jen.Id("text").Op(",").Err().Op(":=").Add(nativeCall(info)),
		jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Lit(""), jen.Err())),
		jen.Return(jen.Id(name).Call(jen.Id("text")), jen.Nil()),
	}
}

// nativePatternOf returns the official regex backing a relaxed native kind.
func nativePatternOf(native string) string {
	switch native {
	case "Quantity64":
		return "^0x(0|[1-9a-f][0-9a-f]{0,15})$"
	case "Quantity256":
		return "^0x(0|[1-9a-f][0-9a-f]{0,63})$"
	case "StorageKey":
		return "^0x[0-9a-f]{0,64}$"
	}
	panic("nativePatternOf: unknown kind " + native)
}

// --- objects ---

func emitObject(f *jen.File, reg *registry, obj *objectModel) {
	emitObjectComment(f, obj)
	f.Type().Id(obj.name).StructFunc(func(g *jen.Group) {
		for _, field := range obj.fields {
			g.Id(field.goName).Add(fieldGoType(&field)).Tag(map[string]string{
				"json": jsonTag(&field),
			})
		}
	})
	emitObjectParse(f, reg, obj)
	emitObjectMarshal(f, obj)
}

// fieldGoType renders the Go type for a struct field. Optional scalars are
// pointers so absent stays absent and null collapses into absence, matching
// the hand-written canonical structs.
func fieldGoType(field *fieldModel) jen.Code {
	if !field.req {
		return jen.Op("*").Id(field.ref.codeName())
	}
	return jen.Id(field.ref.codeName())
}

func jsonTag(field *fieldModel) string {
	if field.req {
		return field.json
	}
	return field.json + ",omitempty"
}

func emitObjectComment(f *jen.File, obj *objectModel) {
	f.Commentf("%s is the execution-apis %s wire object.", obj.name, obj.name)
	f.Comment("Field order is canonical. Optional fields are omitted when the")
	f.Comment("source did not provide them, never filled with null.")
	if len(obj.from) > 1 {
		f.Commentf("Shape shared by: %s.", strings.Join(obj.from, ", "))
	}
}

// fieldShape classifies one field for the parser emitter.
func fieldShape(field *fieldModel) string {
	k := "scalar"
	switch field.ref.kind {
	case refArray:
		k = "array"
	case refUnion:
		k = "union"
	case refObject:
		k = "object"
	case refScalar:
		switch field.ref.native {
		case "bool":
			k = "bool"
		case "int":
			k = "int"
		}
	}
	if !field.req {
		return "ptr" + k
	}
	return k
}

func emitObjectParse(f *jen.File, reg *registry, obj *objectModel) {
	f.Func().Id("New"+obj.name).Params(
		jen.Id("raw").Qual("encoding/json", "RawMessage"),
	).Params(jen.Id(obj.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		name := obj.name
		rawMessage := jen.Qual("encoding/json", "RawMessage")

		g.Comment("Raw spellings are collected first, then validated one by one")
		g.Comment("in canonical field order below.")
		g.Var().Id("fields").StructFunc(func(sg *jen.Group) {
			for _, field := range obj.fields {
				// Every collected field is one RawMessage, including array
				// fields: the raw bytes go through the parse loops below.
				stmt := sg.Id(field.rawName).Add(rawMessage)
				stmt.Tag(map[string]string{"json": field.json})
			}
		})
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
			Call(jen.Id("raw"), jen.Op("&").Id("fields")), jen.Err().Op("!=").Nil()).Block(
			jen.Return(jen.Id(name+"{}"), jen.Qual("fmt", "Errorf").
				Call(jen.Lit(name+": malformed object: %w"), jen.Err())),
		)
		g.Var().Id("out").Id(name)
		needsErr := false
		for _, field := range obj.fields {
			switch fieldShape(&field) {
			case "int", "bool":
				// These parse inside a shadowing "if err := ...".
			case "array", "ptrarray":
				// Loop bodies assign "member, err = ..." with the outer err.
				needsErr = true
			default:
				// Required New*/New<object>/New<union> parses assign the
				// outer err; optional ones shadow it in a block.
				if field.req {
					needsErr = true
				}
			}
		}
		if needsErr {
			g.Var().Id("err").Id("error")
		}

		for _, field := range obj.fields {
			emitFieldParse(g, reg, obj, &field)
		}
		g.Return(jen.Id("out"), jen.Nil())
	})
}

// emitFieldParse emits parse statements for one field, in canonical order.
func emitFieldParse(g *jen.Group, reg *registry, obj *objectModel, field *fieldModel) {
	prefix := obj.name
	name := field.json
	out := jen.Id("out").Dot(field.goName)
	src := jen.Id("fields").Dot(field.rawName)
	fail := func(format string, args ...jen.Code) []jen.Code {
		return []jen.Code{
			jen.Return(jen.Id(prefix+"{}"), jen.Qual("fmt", "Errorf").
				Call(append([]jen.Code{jen.Lit(prefix + ": " + format)}, args...)...)),
		}
	}
	presence := jen.Id("len").Call(src.Clone()).Op("==").Lit(0)
	missing := fail("missing required field %q", jen.Lit(name))

	switch fieldShape(field) {
	case "scalar":
		g.If(presence).Block(missing...)
		g.Add(out.Clone().Op(",").Err().Op("=").Id("New" + field.ref.native).Call(src.Clone()))
		g.If(jen.Err().Op("!=").Nil()).Block(fail(name+": %w", jen.Err())...)
		emitConstChecks(g, field, prefix, name)
		emitPatternChecks(g, reg, field, prefix, name)

	case "int":
		g.If(presence).Block(missing...)
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
			Call(src.Clone(), jen.Op("&").Add(out.Clone())), jen.Err().Op("!=").Nil()).Block(
			fail(name+": expected a number: %w", jen.Err())...,
		)
		emitConstChecks(g, field, prefix, name)

	case "bool":
		g.If(presence).Block(missing...)
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
			Call(src.Clone(), jen.Op("&").Add(out.Clone())), jen.Err().Op("!=").Nil()).Block(
			fail(name+": expected a boolean: %w", jen.Err())...,
		)

	case "union", "object":
		g.If(presence).Block(missing...)
		g.Add(out.Clone().Op(",").Err().Op("=").Id("New" + field.ref.typeName).Call(src.Clone()))
		g.If(jen.Err().Op("!=").Nil()).Block(fail(name+": %w", jen.Err())...)
		emitConstChecks(g, field, prefix, name)

	case "array":
		emitArrayInto(g, field.ref.elem, field.ref.codeName(), src.Clone(), out.Clone(), field.goName, name, 0, fail)

	case "ptrscalar", "ptrbool", "ptrint":
		g.If(jen.Id("PresentNonNull").Call(src.Clone())).BlockFunc(func(bg *jen.Group) {
			native := field.ref.native
			switch native {
			case "bool":
				bg.Var().Id("flag").Bool()
				bg.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
					Call(src.Clone(), jen.Op("&").Id("flag")), jen.Err().Op("!=").Nil()).Block(
					fail(name+": expected a boolean: %w", jen.Err())...,
				)
				bg.Add(out.Clone()).Op("=").Op("&").Id("flag")
			case "int":
				bg.Var().Id("num").Int()
				bg.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
					Call(src.Clone(), jen.Op("&").Id("num")), jen.Err().Op("!=").Nil()).Block(
					fail(name+": expected a number: %w", jen.Err())...,
				)
				bg.Add(out.Clone()).Op("=").Op("&").Id("num")
			default:
				bg.Id("value").Op(",").Err().Op(":=").Id("New" + native).Call(src.Clone())
				bg.If(jen.Err().Op("!=").Nil()).Block(fail(name+": %w", jen.Err())...)
				bg.Add(out.Clone()).Op("=").Op("&").Id("value")
			}
		})

	case "ptrarray":
		// The list variable must outlive the gating if-clause.
		listVar := "list" + field.goName
		g.Var().Id(listVar).Id(field.ref.codeName())
		g.If(src.Clone().Op("!=").Nil()).BlockFunc(func(bg *jen.Group) {
			emitArrayInto(bg, field.ref.elem, field.ref.codeName(), src.Clone(), jen.Id(listVar), field.goName, name, 0, fail)
			bg.Add(out.Clone()).Op("=").Op("&").Id(listVar)
		})
	}
}

// emitArrayInto writes the parse loops for one array destination, recursing
// for arrays of arrays (feeHistory reward) and failing on deeper nesting.
// prefix keeps generated loop variable names unique across sibling fields.
func emitArrayInto(g *jen.Group, elem *ref, arrayType string, src, dst *jen.Statement, prefix, wireName string, depth int, fail func(string, ...jen.Code) []jen.Code) {
	rowsVar := fmt.Sprintf("rows%s%d", prefix, depth)
	idx := fmt.Sprintf("i%s%d", prefix, depth)
	elemVar := fmt.Sprintf("elem%s%d", prefix, depth)
	g.Var().Id(rowsVar).Index().Qual("encoding/json", "RawMessage")
	g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
		Call(src, jen.Op("&").Id(rowsVar)), jen.Err().Op("!=").Nil()).Block(
		fail(wireName+": expected an array: %w", jen.Err())...,
	)
	g.If(jen.Id(rowsVar).Op("==").Nil()).Block(
		fail(wireName + ": expected an array")...,
	)
	g.Add(dst.Clone()).Op("=").Make(jen.Id(arrayType), jen.Len(jen.Id(rowsVar)))
	g.For(jen.Id(idx).Op(",").Id(elemVar).Op(":=").Range().Id(rowsVar)).BlockFunc(func(bg *jen.Group) {
		member := dst.Clone().Index(jen.Id(idx))
		switch elem.kind {
		case refScalar:
			bg.Add(member).Op(",").Err().Op("=").
				Id("New" + elem.native).Call(jen.Id(elemVar))
			bg.If(jen.Err().Op("!=").Nil()).Block(
				fail(wireName+"[%d]: %w", jen.Id(idx), jen.Err())...,
			)
		case refObject, refUnion:
			bg.Add(member).Op(",").Err().Op("=").
				Id("New" + elem.typeName).Call(jen.Id(elemVar))
			bg.If(jen.Err().Op("!=").Nil()).Block(
				fail(wireName+"[%d]: %w", jen.Id(idx), jen.Err())...,
			)
		case refArray:
			emitArrayInto(bg, elem.elem, elem.codeName(), jen.Id(elemVar), member, prefix, wireName, depth+1, fail)
		}
	})
}

// emitConstChecks pins official {"const": v} and literal-pattern fields.
func emitConstChecks(g *jen.Group, field *fieldModel, prefix, name string) {
	if len(field.constValues) == 0 {
		return
	}
	if field.ref.native == "int" {
		for _, literal := range field.constValues {
			value, err := strconv.ParseInt(literal, 10, 64)
			if err != nil {
				panic(fmt.Sprintf("const %q is not an integer literal: %v", literal, err))
			}
			// jen.Lit keeps the type; an untyped comparison literal works
			// for both int and int64 fields, so cast down to int here.
			g.If(jen.Id("out").Dot(field.goName).Op("!=").Lit(int(value))).Block(
				jen.Return(jen.Id(prefix+"{}"), jen.Qual("fmt", "Errorf").
					Call(jen.Lit(prefix+": "+name+": expected constant %s, got %d"),
						jen.Lit(literal), jen.Id("out").Dot(field.goName))),
			)
		}
		return
	}
	for _, literal := range field.constValues {
		text := literal
		if strings.HasPrefix(literal, `"`) {
			text, _ = strconv.Unquote(literal)
		}
		g.If(jen.Id("out").Dot(field.goName).Op("!=").Lit(text)).Block(
			jen.Return(jen.Id(prefix+"{}"), jen.Qual("fmt", "Errorf").
				Call(jen.Lit(prefix+": "+name+": expected constant %s, got %s"),
					jen.Lit(text), jen.Id("out").Dot(field.goName))),
		)
	}
}

// emitPatternChecks applies official regex constraints to Text fields.
func emitPatternChecks(g *jen.Group, reg *registry, field *fieldModel, prefix, name string) {
	for _, pattern := range field.patterns {
		varName, ok := reg.report.patternVars[pattern]
		if !ok {
			varName = fmt.Sprintf("textPattern%d", len(reg.report.patternVars))
			reg.report.patternVars[pattern] = varName
		}
		g.If(jen.Op("!").Id(varName).Dot("MatchString").Call(
			jen.Id("string").Call(jen.Id("out").Dot(field.goName)))).Block(
			jen.Return(jen.Id(prefix+"{}"), jen.Qual("fmt", "Errorf").
				Call(jen.Lit(prefix+": "+name+": does not match the official pattern %s"),
					jen.Lit(pattern))),
		)
	}
}

// emitObjectMarshal writes the ordered marshal method through
// MarshalNoEscape, so field order is the struct order and HTML escaping is
// off, exactly like the hand-written canonical encoders.
func emitObjectMarshal(f *jen.File, obj *objectModel) {
	f.Func().Params(jen.Id("v").Id(obj.name)).Id("MarshalJSON").Params().
		Params(jen.Index().Byte(), jen.Error()).Block(
		jen.Return(jen.Id("MarshalNoEscape").Call(
			jen.StructFunc(func(sg *jen.Group) {
				for _, field := range obj.fields {
					sg.Id(field.goName).Add(fieldGoType(&field)).Tag(map[string]string{
						"json": jsonTag(&field),
					})
				}
			}).ValuesFunc(func(vg *jen.Group) {
				for _, field := range obj.fields {
					vg.Id("v").Dot(field.goName)
				}
			}),
		)),
	)
}

// --- unions ---

// emitUnion writes the tagged union wrapper: official branch order drives
// parse selection, and marshaling delegates to the chosen branch.
func emitUnion(f *jen.File, um *unionModel) {
	f.Commentf("%s is the tagged oneOf union of the official %s branches:", um.name, um.name)
	f.Comment("branch selection follows the official declaration order, and an")
	f.Comment("empty wrapper stands for JSON null where the schema allows it.")
	f.Type().Id(um.name).StructFunc(func(g *jen.Group) {
		for _, branch := range um.branches {
			g.Id(branch.goName).Op("*").Id(branch.ref.codeName()).Tag(map[string]string{"json": "-"})
		}
	})

	// Array branches get a small (T, bool) parser: the official array shape
	// either validates completely or the branch does not match.
	for _, branch := range um.branches {
		if branch.ref.kind != refArray {
			continue
		}
		if branch.ref.elem.kind == refArray {
			panic("emitUnion: arrays of arrays are not a supported union branch: " + um.name)
		}
		f.Commentf("parse%s reports whether raw matches the %s branch of %s.",
			um.name+branch.goName, branch.goName, um.name)
		f.Func().Id("parse"+um.name+branch.goName).Params(
			jen.Id("raw").Qual("encoding/json", "RawMessage"),
		).Params(jen.Id(branch.ref.codeName()), jen.Bool()).BlockFunc(func(g *jen.Group) {
			g.Var().Id("rows").Index().Qual("encoding/json", "RawMessage")
			g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
				Call(jen.Id("raw"), jen.Op("&").Id("rows")), jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Nil(), jen.False()),
			)
			g.If(jen.Id("rows").Op("==").Nil()).Block(
				jen.Return(jen.Nil(), jen.False()),
			)
			g.Id("list").Op(":=").Make(jen.Id(branch.ref.codeName()), jen.Len(jen.Id("rows")))
			g.Var().Id("err").Id("error")
			g.For(jen.Id("i, elem").Op(":=").Range().Id("rows")).Block(
				jen.Id("list").Index(jen.Id("i")).Op(",").Err().Op("=").
					Id("New"+branch.ref.elem.codeName()).Call(jen.Id("elem")),
				jen.If(jen.Err().Op("!=").Nil()).Block(
					jen.Return(jen.Nil(), jen.False()),
				),
			)
			g.Return(jen.Id("list"), jen.True())
		})
	}

	// Parse: each branch attempt runs in its own block scope; the first
	// branch whose official shape validates wins.
	f.Func().Id("New"+um.name).Params(
		jen.Id("raw").Qual("encoding/json", "RawMessage"),
	).Params(jen.Id(um.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		if um.nullable {
			g.If(jen.Id("IsJSONNull").Call(jen.Id("raw"))).Block(
				jen.Return(jen.Id(um.name+"{}"), jen.Nil()),
			)
		}
		for _, branch := range um.branches {
			g.Add(jen.BlockFunc(func(bg *jen.Group) {
				switch branch.ref.kind {
				case refScalar:
					if branch.ref.native == "bool" {
						// No generated parser exists for raw bool: unmarshal
						// directly in the branch scope.
						bg.Var().Id("value").Bool()
						bg.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").
							Call(jen.Id("raw"), jen.Op("&").Id("value")), jen.Err().Op("==").Nil()).Block(
							jen.Return(jen.Id(um.name).Values(
								jen.Id(branch.goName).Op(":").Op("&").Id("value")), jen.Nil()),
						)
						break
					}
					bg.Id("text").Op(",").Err().Op(":=").
						Id("New" + branch.ref.native).Call(jen.Id("raw"))
					bg.If(jen.Err().Op("==").Nil()).Block(
						jen.Return(jen.Id(um.name).Values(
							jen.Id(branch.goName).Op(":").Op("&").Id("text")), jen.Nil()),
					)
				case refArray:
					bg.If(jen.Id("value").Op(",").Id("ok").Op(":=").Add(unionTryFuncName(um, branch)).
						Call(jen.Id("raw")), jen.Id("ok")).Block(
						jen.Return(jen.Id(um.name).Values(
							jen.Id(branch.goName).Op(":").Op("&").Id("value")), jen.Nil()),
					)
				default:
					bg.Id("value").Op(",").Err().Op(":=").
						Id("New" + branch.ref.codeName()).Call(jen.Id("raw"))
					bg.If(jen.Err().Op("==").Nil()).Block(
						jen.Return(jen.Id(um.name).Values(
							jen.Id(branch.goName).Op(":").Op("&").Id("value")), jen.Nil()),
					)
				}
			}))
		}
		g.Return(jen.Id(um.name+"{}"), jen.Qual("fmt", "Errorf").
			Call(jen.Lit(um.name+": value matches no official branch")))
	})

	// Marshal: delegate to the selected branch.
	f.Func().Params(jen.Id("u").Id(um.name)).Id("MarshalJSON").Params().
		Params(jen.Index().Byte(), jen.Error()).BlockFunc(func(g *jen.Group) {
		for _, branch := range um.branches {
			// Scalars and slices have no MarshalJSON of their own: their
			// bytes go through MarshalNoEscape just like the native types.
			marshalDirect := branch.ref.kind == refScalar || branch.ref.kind == refArray
			if marshalDirect {
				g.If(jen.Id("u").Dot(branch.goName).Op("!=").Nil()).Block(
					jen.Return(jen.Id("MarshalNoEscape").Call(
						jen.Op("*").Id("u").Dot(branch.goName))),
				)
				continue
			}
			g.If(jen.Id("u").Dot(branch.goName).Op("!=").Nil()).Block(
				jen.Return(jen.Id("u").Dot(branch.goName).Dot("MarshalJSON").Call()),
			)
		}
		g.Return(jen.Nil(), jen.Qual("fmt", "Errorf").
			Call(jen.Lit(um.name+": empty union cannot marshal")))
	})
}

// unionTryFuncName is the generated (T, bool) parser for one array branch.
func unionTryFuncName(um *unionModel, branch branchModel) *jen.Statement {
	return jen.Id("parse" + um.name + branch.goName)
}

// --- method result shims ---

// emitRoots writes per-method result functions for roots whose official
// schema needs null-handling or array handling at the root.
func emitRoots(f *jen.File, reg *registry, roots map[string]*ref) {
	methods := make([]string, 0, len(roots))
	for method := range roots {
		methods = append(methods, method)
	}
	sort.Strings(methods)
	for _, method := range methods {
		emitRootShim(f, method, roots[method])
	}
	reg.report.countShims = len(methods)
	reg.report.countUnions = len(reg.unionList)
}

func emitRootShim(f *jen.File, method string, root *ref) {
	if root == nil {
		return
	}
	rawMessage := jen.Qual("encoding/json", "RawMessage")
	switch root.kind {
	case refObject, refUnion:
		if !root.pointer {
			return // New<Type> already covers these roots
		}
		f.Commentf("%s parses one %s result: JSON null (Not Found) stays nil.",
			methodShimName(method), method)
		f.Func().Id(methodShimName(method)).Params(
			jen.Id("raw").Add(rawMessage),
		).Params(jen.Op("*").Id(root.codeName()), jen.Error()).Block(
			jen.If(jen.Id("IsJSONNull").Call(jen.Id("raw"))).Block(
				jen.Return(jen.Nil(), jen.Nil()),
			),
			jen.Id("value, err :=").Id("New"+root.codeName()).Call(jen.Id("raw")),
			jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Nil(), jen.Err())),
			jen.Return(jen.Op("&").Id("value"), jen.Nil()),
		)
	case refArray:
		f.Commentf("%s parses one %s result: JSON null (Not Found) stays nil.", methodShimName(method), method)
		f.Func().Id(methodShimName(method)).Params(
			jen.Id("raw").Add(rawMessage),
		).Params(jen.Id(root.codeName()), jen.Error()).BlockFunc(func(g *jen.Group) {
			fail := func(format string, args ...jen.Code) []jen.Code {
				return []jen.Code{
					jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").
						Call(append([]jen.Code{jen.Lit(method + ": " + format)}, args...)...)),
				}
			}
			if root.pointer {
				g.If(jen.Id("IsJSONNull").Call(jen.Id("raw"))).Block(
					jen.Return(jen.Nil(), jen.Nil()),
				)
			}
			g.Var().Id("list").Id(root.codeName())
			g.Var().Id("err").Id("error")
			emitArrayInto(g, root.elem, root.codeName(), jen.Id("raw"), jen.Id("list"), methodCamel(method), "", 0, fail)
			g.Return(jen.Id("list"), jen.Nil())
		})
	}
}

func methodShimName(method string) string {
	return "New" + methodCamel(method) + "Result"
}

func methodCamel(method string) string {
	trimmed := strings.TrimPrefix(method, "eth_")
	trimmed = strings.TrimPrefix(trimmed, "net_")
	if trimmed == "" {
		trimmed = method
	}
	// Insert separators before a digit run: simulateV1 -> SimulateV1 keeps
	// its shape; numbers are part of the official name.
	return strings.ToUpper(trimmed[:1]) + trimmed[1:]
}
