package main

// Schema semantics are resolved by walk. This file renders that model with
// Jennifer; it neither changes schemas nor interprets them at runtime.
import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/dave/jennifer/jen"
)

const specPackage = "github.com/codermaybe/ethguard/internal/spec"
const safePackage = "github.com/codermaybe/ethguard/internal/jsonsafe"
const codecPackage = "github.com/codermaybe/ethguard/internal/ethcodec"

type genReport struct {
	nameCollisions                                []collision
	visited                                       map[string]bool
	methods                                       []string
	errata                                        []string
	objects, countFields, countUnions, countShims int
}

func emit(reg *registry, version string, roots map[string]*ref, outPath string) error {
	reg.report.countUnions = len(reg.unionList)
	reg.report.countShims = 0
	for method, r := range roots {
		if !rootUsesConstructor(method, r) {
			reg.report.countShims++
		}
	}
	f := jen.NewFilePathName("github.com/codermaybe/ethguard/ethapi", "ethapi")
	f.HeaderComment(fmt.Sprintf("Code generated by rpc/internal/wire/gen from execution-apis %s; DO NOT EDIT.", version))
	for _, applied := range reg.report.errata {
		f.HeaderComment("Reviewed schema erratum: " + applied)
	}
	f.HeaderComment("Typed official values preserve constraints, declared composition kind and nullable presence.")
	f.HeaderComment("Constructors enforce schema constraints. Directly constructed typed values must preserve those invariants;")
	f.HeaderComment("marshaling encodes once without revalidation, except for union member selection checks.")
	f.HeaderComment(fmt.Sprintf("Built from %d methods: %d object types, %d fields, %d unions, %d result shims.",
		len(reg.report.methods), reg.report.objects, reg.report.countFields, reg.report.countUnions, reg.report.countShims))
	f.Const().Id("generatedBundleVersion").Op("=").Lit(version)
	f.Func().Id("init").Params().Block(
		jen.If(jen.Id("v").Op(":=").Qual(specPackage, "Version").Call(),
			jen.Id("v").Op("!=").Id("generatedBundleVersion")).Block(
			jen.Panic(jen.Qual("fmt", "Sprintf").Call(
				jen.Lit("wire: generated spec %q != pin %q"), jen.Id("generatedBundleVersion"), jen.Id("v"))),
		),
	)
	for _, n := range natives {
		emitNative(f, n)
	}
	for _, r := range reg.values {
		emitValue(f, r)
	}
	for _, dictionary := range reg.maps {
		emitDictionary(f, dictionary)
	}
	for _, obj := range reg.objects {
		emitObject(f, obj)
	}
	for _, u := range reg.unionList {
		emitUnion(f, u)
	}
	aliases := make([]string, 0, len(modelAliases))
	for alias := range modelAliases {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		target := modelAliases[alias]
		if !reg.usedNames[target] {
			continue
		}
		f.Commentf("%s aliases the shared official %s model.", alias, target)
		f.Type().Id(alias).Op("=").Id(target)
		f.Func().Id("New"+alias).Params(rawParameter()).Params(jen.Id(alias), jen.Error()).Block(jen.Return(jen.Id("New" + target).Call(jen.Id("raw"))))
	}

	methods := make([]string, 0, len(roots))
	for method := range roots {
		methods = append(methods, method)
	}
	sort.Strings(methods)
	for _, method := range methods {
		r := roots[method]
		if rootUsesConstructor(method, r) {
			continue
		}
		f.Commentf("%s parses the complete official %s result.", methodShimName(method), method)
		f.Func().Id(methodShimName(method)).Params(rawParameter()).Params(typeCode(r), jen.Error()).Block(
			jen.Return(jen.Id(r.parser).Call(jen.Id("raw"), jen.False())),
		)
	}
	if err := f.Save(outPath); err != nil {
		return fmt.Errorf("emit: %w", err)
	}
	return nil
}

func rootUsesConstructor(method string, r *ref) bool {
	return !r.pointer && (r.kind == refObject || r.kind == refUnion) && methodShimName(method) == "New"+r.typeName
}

func rawParameter() *jen.Statement {
	return jen.Id("raw").Qual("encoding/json", "RawMessage")
}

func keepStringsParameter() *jen.Statement {
	return jen.Id("keepStrings").Bool()
}

func errorf(message string, args ...jen.Code) *jen.Statement {
	return jen.Qual("fmt", "Errorf").Call(append([]jen.Code{jen.Lit(message)}, args...)...)
}

func typeCode(r *ref) *jen.Statement {
	var code *jen.Statement
	if r.kind == refArray {
		code = jen.Index().Add(typeCode(r.elem))
	} else if r.kind == refScalar {
		code = jen.Id(r.native)
	} else {
		code = jen.Id(r.typeName)
	}
	if r.pointer {
		return jen.Op("*").Add(code)
	}
	return code
}

func emitNative(f *jen.File, n nativeDescriptor) {
	f.Commentf("%s is the %s.", n.name, n.doc)
	f.Type().Id(n.name).String()
	pattern := "native" + n.name + "Pattern"
	fixedHexDigits := fixedLowerHexPatternDigits(n.pattern)
	if n.pattern != "" && fixedHexDigits == 0 {
		f.Var().Id(pattern).Op("=").Qual("regexp", "MustCompile").Call(jen.Lit(n.pattern))
	}
	constructor := "New" + n.name
	parameters := []jen.Code{rawParameter()}
	if n.rewritesString() {
		f.Func().Id(constructor).Params(rawParameter()).Params(jen.Id(n.name), jen.Error()).Block(
			jen.Return(jen.Id("parse"+n.name).Call(jen.Id("raw"), jen.False())),
		)
		constructor = "parse" + n.name
		parameters = append(parameters, keepStringsParameter())
	}
	f.Func().Id(constructor).Params(parameters...).Params(jen.Id(n.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(
			jen.Return(jen.Lit(""), errorf(n.name+": expected a non-null value")),
		)
		if n.representation == exactNumber {
			g.List(jen.Id("number"), jen.Err()).Op(":=").Qual(codecPackage, "CanonicalNumber").Call(jen.Id("raw"))
			g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Lit(""), jen.Err()))
			g.Return(jen.Id(n.name).Call(jen.Id("number").Dot("String").Call()), jen.Nil())
			return
		}
		g.Var().Id("text").String()
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("text")), jen.Err().Op("!=").Nil()).Block(
			jen.Return(jen.Lit(""), errorf("expected string: %w", jen.Err())),
		)
		if n.pattern != "" {
			match := jen.Id(pattern).Dot("MatchString").Call(jen.Id("text"))
			if fixedHexDigits != 0 {
				match = jen.Qual(codecPackage, "IsLowerFixedHex").Call(jen.Id("text"), jen.Lit(fixedHexDigits))
			}
			g.If(jen.Op("!").Add(match)).Block(
				jen.Return(jen.Lit(""), errorf(n.name+": invalid input spelling %q", jen.Id("text"))),
			)
		}
		if n.rewritesString() {
			g.If(jen.Id("keepStrings")).Block(jen.Return(jen.Id(n.name).Call(jen.Id("text")), jen.Nil()))
		}
		switch n.representation {
		case lowercaseAddress:
			g.Id("text").Op("=").Qual("strings", "ToLower").Call(jen.Id("text"))
		case minimalHexByte:
			g.If(jen.Len(jen.Id("text")).Op("==").Lit(4).Op("&&").Id("text").Index(jen.Lit(2)).Op("==").Lit(byte('0'))).Block(
				jen.Id("text").Op("=").Lit("0x").Op("+").Id("text").Index(jen.Lit(3), jen.Empty()),
			)
		}
		g.Return(jen.Id(n.name).Call(jen.Id("text")), jen.Nil())
	})
	f.Func().Params(jen.Id("v").Id(n.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).BlockFunc(func(g *jen.Group) {
		if n.representation == exactNumber {
			g.Return(jen.Index().Byte().Call(jen.Id("v")), jen.Nil())
		} else {
			g.Return(jen.Qual(codecPackage, "MarshalNoEscape").Call(jen.String().Call(jen.Id("v"))))
		}
	})
}

// Specialize only these reviewed native patterns. A different spelling or
// future schema pattern keeps the regular-expression implementation.
func fixedLowerHexPatternDigits(pattern string) int {
	switch pattern {
	case `^0x[0-9a-f]{64}$`:
		return 64
	case `^0x[0-9a-f]{512}$`:
		return 512
	case `^0x[0-9a-f]{16}$`:
		return 16
	default:
		return 0
	}
}

func emitValue(f *jen.File, r *ref) {
	pattern := r.pattern
	if nativeForPattern(pattern) == r.native {
		pattern = ""
	}
	if pattern != "" {
		f.Var().Id(r.parser+"Pattern").Op("=").Qual("regexp", "MustCompile").Call(jen.Lit(pattern))
	}
	f.Func().Id(r.parser).Params(rawParameter(), keepStringsParameter()).Params(typeCode(r), jen.Error()).BlockFunc(func(g *jen.Group) {
		if r.pointer {
			g.If(jen.Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(jen.Return(jen.Nil(), jen.Nil()))
			g.List(jen.Id("value"), jen.Err()).Op(":=").Id(r.inner.parser).Call(jen.Id("raw"), jen.Id("keepStrings"))
			g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Nil(), jen.Err()))
			g.Return(jen.Op("&").Id("value"), jen.Nil())
			return
		}
		g.Var().Id("out").Add(typeCode(r))
		if r.kind != refUnion {
			g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(
				jen.Return(jen.Id("out"), errorf(r.path+": expected a non-null value")),
			)
		}
		switch r.kind {
		case refScalar:
			if r.native == "int" {
				g.List(jen.Id("number"), jen.Err()).Op(":=").Qual(codecPackage, "CanonicalNumber").Call(jen.Id("raw"))
				g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(r.path+": %w", jen.Err())))
				g.If(jen.Qual(codecPackage, "CompareNumbers").Call(jen.Id("number"), jen.Qual("encoding/json", "Number").Call(jen.Lit(fmt.Sprint(r.constant)))).Op("!=").Lit(0)).Block(
					jen.Return(jen.Id("out"), errorf(r.path+": expected constant")),
				)
				g.Id("out").Op("=").Add(constCode(r.constant))
			} else if r.native == "bool" {
				g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("out")), jen.Err().Op("!=").Nil()).Block(
					jen.Return(jen.Id("out"), errorf(r.path+": %w", jen.Err())),
				)
			} else {
				parse := jen.Id("New" + r.native).Call(jen.Id("raw"))
				if nativeRewritesString(r.native) {
					parse = jen.Id("parse"+r.native).Call(jen.Id("raw"), jen.Id("keepStrings"))
				}
				g.List(jen.Id("value"), jen.Err()).Op(":=").Add(parse)
				g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(r.path+": %w", jen.Err())))
				g.Id("out").Op("=").Id("value")
			}
		case refObject, refUnion, refMap:
			g.List(jen.Id("value"), jen.Err()).Op(":=").Id("parse"+r.typeName).Call(jen.Id("raw"), jen.Id("keepStrings"))
			g.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), jen.Err()))
			g.Id("out").Op("=").Id("value")
		case refArray:
			g.Var().Id("rows").Index().Qual("encoding/json", "RawMessage")
			g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("rows")), jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Id("out"), errorf(r.path+": expected array: %w", jen.Err())),
			)
			g.Id("out").Op("=").Make(typeCode(r), jen.Len(jen.Id("rows")))
			g.For(jen.List(jen.Id("i"), jen.Id("row")).Op(":=").Range().Id("rows")).Block(
				jen.List(jen.Id("value"), jen.Err()).Op(":=").Id(r.elem.parser).Call(jen.Id("row"), jen.Id("keepStrings")),
				jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(r.path+"[%d]: %w", jen.Id("i"), jen.Err()))),
				jen.Id("out").Index(jen.Id("i")).Op("=").Id("value"),
			)
		}
		if r.kind == refArray {
			if r.minItems != nil {
				g.If(jen.Len(jen.Id("out")).Op("<").Lit(*r.minItems)).Block(jen.Return(jen.Id("out"), errorf(r.path+": fewer than minItems")))
			}
			if r.maxItems != nil {
				g.If(jen.Len(jen.Id("out")).Op(">").Lit(*r.maxItems)).Block(jen.Return(jen.Id("out"), errorf(r.path+": more than maxItems")))
			}
			if r.uniqueItems {
				emitUniqueItems(g, r)
			}
		}
		if r.hasEnum {
			emitEnumCheck(g, r)
		}
		if r.hasConst && r.native != "int" {
			var condition *jen.Statement
			if r.native == "Number" {
				condition = compareNumber(fmt.Sprint(r.constant)).Op("!=").Lit(0)
			} else {
				condition = jen.Id("out").Op("!=").Add(constCode(r.constant))
			}
			g.If(condition).Block(jen.Return(jen.Id("out"), errorf(r.path+": expected constant")))
		}
		if pattern != "" {
			g.If(jen.Op("!").Id(r.parser + "Pattern").Dot("MatchString").Call(jen.String().Call(jen.Id("out")))).Block(
				jen.Return(jen.Id("out"), errorf(r.path+": does not match official pattern")),
			)
		}
		if r.minimum != nil {
			g.If(compareNumber(r.minimum.String()).Op("<").Lit(0)).Block(jen.Return(jen.Id("out"), errorf(r.path+": below official minimum")))
		}
		if r.maximum != nil {
			g.If(compareNumber(r.maximum.String()).Op(">").Lit(0)).Block(jen.Return(jen.Id("out"), errorf(r.path+": above official maximum")))
		}
		g.Return(jen.Id("out"), jen.Nil())
	})
}

func compareNumber(value string) *jen.Statement {
	return jen.Qual(codecPackage, "CompareNumbers").Call(
		jen.Qual("encoding/json", "Number").Call(jen.Id("out")),
		jen.Qual("encoding/json", "Number").Call(jen.Lit(value)),
	)
}

func constCode(value any) *jen.Statement {
	if number, ok := value.(json.Number); ok {
		// Non-integer numeric constants are compared as exact Number values.
		// Keep the walker's portable int range before converting on any host.
		integer, err := strconv.ParseInt(number.String(), 10, 32)
		if err != nil {
			panic(fmt.Sprintf("emit: invalid integer constant %q: %v", number, err))
		}
		return jen.Lit(int(integer))
	}
	return jen.Lit(value)
}

func fieldTypeCode(f fieldModel) *jen.Statement {
	if !f.req {
		return jen.Op("*").Add(typeCode(f.ref))
	}
	return typeCode(f.ref)
}

func fieldTag(f fieldModel) string {
	if !f.req {
		return f.json + ",omitempty"
	}
	return f.json
}

func emitFields(g *jen.Group, obj *objectModel) {
	if obj.retainAdditional {
		g.Id("AdditionalProperties").Map(jen.String()).Qual("encoding/json", "RawMessage").Tag(map[string]string{"json": "-"})
	}
	for _, field := range obj.fields {
		g.Id(field.goName).Add(fieldTypeCode(field)).Tag(map[string]string{"json": fieldTag(field)})
	}
}

func emitObject(f *jen.File, obj *objectModel) {
	f.Commentf("%s is the official execution-apis object; optional nullable fields distinguish absence from null.", obj.name)
	f.Commentf("New%s enforces schema constraints; directly constructed values must preserve those invariants.", obj.name)
	if len(obj.from) > 1 {
		f.Commentf("Shape shared by: %s.", strings.Join(obj.from, ", "))
	}
	f.Type().Id(obj.name).StructFunc(func(g *jen.Group) { emitFields(g, obj) })
	emitConstructor(f, obj.name, obj.request)
	f.Func().Id("parse"+obj.name).Params(rawParameter(), keepStringsParameter()).Params(jen.Id(obj.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Var().Id("out").Id(obj.name)
		g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(
			jen.Return(jen.Id("out"), errorf(obj.name+": expected a non-null object")),
		)
		g.Var().Id("members").Map(jen.String()).Qual("encoding/json", "RawMessage")
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("members")), jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(obj.name+": expected object: %w", jen.Err())))
		if obj.hasForbiddenRequired {
			emitForbiddenRequired(g, obj)
		}
		if obj.closed || obj.retainAdditional {
			emitAdditionalMembers(g, obj)
		}

		for _, field := range obj.fields {
			rawField := jen.Id("members").Index(jen.Lit(field.json))
			g.If(jen.Len(rawField).Op("==").Lit(0)).BlockFunc(func(missing *jen.Group) {
				if field.req {
					missing.Return(jen.Id("out"), errorf(obj.name+": missing required field "+field.json))
				}
			}).Else().BlockFunc(func(present *jen.Group) {
				present.List(jen.Id("value"), jen.Err()).Op(":=").Id(field.ref.parser).Call(rawField, jen.Id("keepStrings"))
				present.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), jen.Err()))
				value := jen.Id("value")
				if !field.req {
					value = jen.Op("&").Id("value")
				}
				present.Id("out").Dot(field.goName).Op("=").Add(value)
			})
		}
		g.Return(jen.Id("out"), jen.Nil())
	})
	if obj.retainAdditional {
		emitOpenObjectMarshal(f, obj)
		return
	}
	values := jen.Dict{}
	for _, field := range obj.fields {
		values[jen.Id(field.goName)] = jen.Id("v").Dot(field.goName)
	}
	f.Func().Params(jen.Id("v").Id(obj.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).Block(
		jen.Return(jen.Qual(codecPackage, "MarshalNoEscape").Call(
			jen.StructFunc(func(g *jen.Group) { emitFields(g, obj) }).Values(values),
		)),
	)
}

func emitUnion(f *jen.File, u *unionModel) {
	f.Commentf("%s retains the official %s branches in declaration order.", u.name, u.kind)
	if u.kind == "anyOf" {
		f.Comment("Multiple matching schemas are valid; the first successful branch is the canonical representation.")
	} else {
		f.Comment("Exactly one complete branch must validate.")
	}
	if len(u.from) > 1 {
		f.Commentf("Shape shared by: %s.", strings.Join(u.from, ", "))
	}
	f.Type().Id(u.name).StructFunc(func(g *jen.Group) {
		for _, b := range u.branches {
			g.Commentf("Official %s[%d]: %s.", u.kind, b.index, b.title)
			g.Id(b.goName).Op("*").Add(typeCode(b.ref)).Tag(map[string]string{"json": "-"})
		}
	})
	emitConstructor(f, u.name, u.request)
	f.Func().Id("parse"+u.name).Params(rawParameter(), keepStringsParameter()).Params(jen.Id(u.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Var().Id("out").Id(u.name)
		// Competing branches inspect JSON string identity. Preserve it through
		// every selected child so representation cannot create a new match.
		branchKeepStrings := jen.Id("keepStrings")
		if len(u.branches) > 1 {
			branchKeepStrings = jen.True()
		}
		// anyOf returns on the first accepted branch, so it needs no match
		// counter: falling off the end of the constructor means zero branches
		// accepted, and the terminal error says so without a dead variable.
		if u.kind == "oneOf" {
			g.Id("matches").Op(":=").Lit(0)
		}
		if u.nullable {
			g.If(jen.Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).BlockFunc(func(null *jen.Group) {
				if u.kind == "anyOf" {
					null.Return(jen.Id("out"), jen.Nil())
				} else {
					null.Id("matches").Op("++")
				}
			})
		}
		for _, b := range u.branches {
			g.If(jen.List(jen.Id("value"), jen.Err()).Op(":=").Id(b.ref.parser).Call(jen.Id("raw"), branchKeepStrings), jen.Err().Op("==").Nil()).BlockFunc(func(match *jen.Group) {
				if u.kind == "oneOf" {
					match.Id("matches").Op("++")
				}
				match.Id("out").Dot(b.goName).Op("=").Op("&").Id("value")
				if u.kind == "anyOf" {
					match.Return(jen.Id("out"), jen.Nil())
				}
			})
		}
		if u.kind == "anyOf" {
			// Every anyOf exit is already a return: the in-loop match return,
			// the nullable early return, and this unconditional zero-match
			// error. A trailing success return here would be unreachable code
			// that go vet rejects in the generated source.
			g.Return(jen.Id(u.name).Values(), errorf(u.name+": expected anyOf branch match"))
		} else {
			g.If(jen.Id("matches").Op("!=").Lit(1)).Block(
				jen.Return(jen.Id(u.name).Values(), errorf(u.name+": expected oneOf branch match, got %d", jen.Id("matches"))),
			)
			g.Return(jen.Id("out"), jen.Nil())
		}
	})
	f.Func().Params(jen.Id("u").Id(u.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Id("selected").Op(":=").Lit(0)
		for _, b := range u.branches {
			g.If(jen.Id("u").Dot(b.goName).Op("!=").Nil()).Block(jen.Id("selected").Op("++"))
		}
		if u.nullable {
			g.If(jen.Id("selected").Op("==").Lit(0)).Block(jen.Return(jen.Index().Byte().Call(jen.Lit("null")), jen.Nil()))
		}
		g.If(jen.Id("selected").Op("!=").Lit(1)).Block(
			jen.Return(jen.Nil(), errorf(u.name+": expected exactly one selected member, got %d", jen.Id("selected"))),
		)
		for i, b := range u.branches {
			result := jen.Id("u").Dot(b.goName).Dot("MarshalJSON").Call()
			if b.ref.pointer || b.ref.kind == refScalar || b.ref.kind == refArray {
				result = jen.Qual(codecPackage, "MarshalNoEscape").Call(jen.Op("*").Id("u").Dot(b.goName))
			}
			if i < len(u.branches)-1 {
				g.If(jen.Id("u").Dot(b.goName).Op("!=").Nil()).Block(jen.Return(result))
			} else {
				g.Return(result)
			}
		}
	})
}

func methodShimName(method string) string { return "New" + methodCamel(method) + "Result" }
func methodCamel(method string) string {
	trimmed := strings.TrimPrefix(method, "eth_")
	trimmed = strings.TrimPrefix(trimmed, "net_")
	if trimmed == "" {
		trimmed = method
	}
	return strings.ToUpper(trimmed[:1]) + trimmed[1:]
}

func emitForbiddenRequired(g *jen.Group, obj *objectModel) {
	g.Id("forbidden").Op(":=").True()
	for _, key := range obj.forbiddenRequired {
		g.If(jen.List(jen.Id("_"), jen.Id("present")).Op(":=").Id("members").Index(jen.Lit(key)), jen.Op("!").Id("present")).Block(jen.Id("forbidden").Op("=").False())
	}
	g.If(jen.Id("forbidden")).Block(jen.Return(jen.Id("out"), errorf(obj.name+": forbidden required-field combination")))
}

func emitAdditionalMembers(g *jen.Group, obj *objectModel) {
	g.For(jen.List(jen.Id("key"), jen.Id("member")).Op(":=").Range().Id("members")).BlockFunc(func(loop *jen.Group) {
		if len(obj.propertyNames) > 0 {
			loop.Switch(jen.Id("key")).BlockFunc(func(cases *jen.Group) {
				keys := []jen.Code{}
				for _, key := range obj.propertyNames {
					keys = append(keys, jen.Lit(key))
				}
				cases.Case(keys...).Block(jen.Continue())
			})
		}
		if obj.closed {
			loop.Id("_").Op("=").Id("member")
			loop.Return(jen.Id("out"), errorf(obj.name+": unknown property %q", jen.Id("key")))
		} else {
			loop.If(jen.Id("out").Dot("AdditionalProperties").Op("==").Nil()).Block(jen.Id("out").Dot("AdditionalProperties").Op("=").Make(jen.Map(jen.String()).Qual("encoding/json", "RawMessage")))
			loop.Id("out").Dot("AdditionalProperties").Index(jen.Id("key")).Op("=").Id("member")
		}
	})
}

func emitOpenObjectMarshal(f *jen.File, obj *objectModel) {
	f.Func().Params(jen.Id("v").Id(obj.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Id("members").Op(":=").Make(jen.Map(jen.String()).Any())
		g.For(jen.List(jen.Id("key"), jen.Id("member")).Op(":=").Range().Id("v").Dot("AdditionalProperties")).BlockFunc(func(loop *jen.Group) {
			if len(obj.propertyNames) > 0 {
				loop.Switch(jen.Id("key")).BlockFunc(func(cases *jen.Group) {
					keys := []jen.Code{}
					for _, key := range obj.propertyNames {
						keys = append(keys, jen.Lit(key))
					}
					cases.Case(keys...).Block(jen.Return(jen.Nil(), errorf(obj.name+": additional property %q collides with a declared field", jen.Id("key"))))
				})
			}
			loop.If(jen.Err().Op(":=").Qual(safePackage, "Validate").Call(jen.Id("member")), jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Nil(), errorf(obj.name+": additional property %q: %w", jen.Id("key"), jen.Err())))
			loop.Id("members").Index(jen.Id("key")).Op("=").Id("member")
		})
		for _, field := range obj.fields {
			assignment := jen.Id("members").Index(jen.Lit(field.json)).Op("=")
			if field.req {
				g.Add(assignment).Id("v").Dot(field.goName)
			} else {
				g.If(jen.Id("v").Dot(field.goName).Op("!=").Nil()).Block(assignment.Op("*").Id("v").Dot(field.goName))
			}
		}
		g.Return(jen.Qual(codecPackage, "MarshalNoEscape").Call(jen.Id("members")))
	})
}

func emitEnumCheck(g *jen.Group, r *ref) {
	failures := []jen.Code{}
	for _, value := range r.enumValues {
		switch value := value.(type) {
		case string:
			if r.native != "bool" && r.native != "int" && r.native != "Number" {
				failures = append(failures, jen.String().Call(jen.Id("out")).Op("!=").Lit(value))
			}
		case bool:
			if r.native == "bool" {
				failures = append(failures, jen.Id("out").Op("!=").Lit(value))
			}
		case json.Number:
			if r.native == "Number" {
				failures = append(failures, compareNumber(value.String()).Op("!=").Lit(0))
			}
		}
	}
	condition := jen.True()
	if len(failures) > 0 {
		condition = jen.Add(failures[0])
		for _, failure := range failures[1:] {
			condition.Op("&&").Add(failure)
		}
	}
	g.If(condition).Block(jen.Return(jen.Id("out"), errorf(r.path+": value is outside enum")))
}

func emitUniqueItems(g *jen.Group, r *ref) {
	g.Id("canonicalItems").Op(":=").Make(jen.Index().Qual("encoding/json", "RawMessage"), jen.Len(jen.Id("out")))
	g.For(jen.List(jen.Id("i"), jen.Id("item")).Op(":=").Range().Id("out")).BlockFunc(func(loop *jen.Group) {
		loop.List(jen.Id("canonical"), jen.Err()).Op(":=").Qual(codecPackage, "MarshalNoEscape").Call(jen.Id("item"))
		loop.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), jen.Err()))
		loop.For(jen.List(jen.Id("_"), jen.Id("previous")).Op(":=").Range().Id("canonicalItems").Index(jen.Empty(), jen.Id("i"))).Block(
			jen.List(jen.Id("equal"), jen.Err()).Op(":=").Qual(codecPackage, "JSONValuesEqual").Call(jen.Id("canonical"), jen.Id("previous")),
			jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), jen.Err())),
			jen.If(jen.Id("equal")).Block(jen.Return(jen.Id("out"), errorf(r.path+": duplicate array item"))),
		)
		loop.Id("canonicalItems").Index(jen.Id("i")).Op("=").Id("canonical")
	})
}

func emitDictionary(f *jen.File, m *mapModel) {
	f.Commentf("%s is the official pattern-keyed dictionary.", m.name)
	f.Type().Id(m.name).Map(jen.String()).Add(typeCode(m.elem))
	for i, pattern := range m.patterns {
		f.Var().Id(m.name+"KeyPattern"+itoa(i)).Op("=").Qual("regexp", "MustCompile").Call(jen.Lit(pattern))
	}
	emitConstructor(f, m.name, m.request)
	f.Func().Id("parse"+m.name).Params(rawParameter(), keepStringsParameter()).Params(jen.Id(m.name), jen.Error()).BlockFunc(func(g *jen.Group) {
		g.Var().Id("out").Id(m.name)
		g.If(jen.Len(jen.Id("raw")).Op("==").Lit(0).Op("||").Qual(codecPackage, "IsJSONNull").Call(jen.Id("raw"))).Block(jen.Return(jen.Id("out"), errorf(m.path+": expected a non-null object")))
		g.Var().Id("members").Map(jen.String()).Qual("encoding/json", "RawMessage")
		g.If(jen.Err().Op(":=").Qual("encoding/json", "Unmarshal").Call(jen.Id("raw"), jen.Op("&").Id("members")), jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(m.path+": expected object: %w", jen.Err())))
		g.Id("out").Op("=").Make(jen.Id(m.name), jen.Len(jen.Id("members")))
		g.For(jen.List(jen.Id("key"), jen.Id("member")).Op(":=").Range().Id("members")).BlockFunc(func(loop *jen.Group) {
			valid := jen.False()
			for i := range m.patterns {
				valid.Op("||").Id(m.name + "KeyPattern" + itoa(i)).Dot("MatchString").Call(jen.Id("key"))
			}
			loop.If(jen.Op("!").Parens(valid)).Block(jen.Return(jen.Id("out"), errorf(m.path+": unknown dictionary key %q", jen.Id("key"))))
			loop.List(jen.Id("value"), jen.Err()).Op(":=").Id(m.elem.parser).Call(jen.Id("member"), jen.Id("keepStrings"))
			loop.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Id("out"), errorf(m.path+"[%q]: %w", jen.Id("key"), jen.Err())))
			loop.Id("out").Index(jen.Id("key")).Op("=").Id("value")
		})
		g.Return(jen.Id("out"), jen.Nil())
	})
	f.Func().Params(jen.Id("v").Id(m.name)).Id("MarshalJSON").Params().Params(jen.Index().Byte(), jen.Error()).Block(jen.Return(jen.Qual(codecPackage, "MarshalNoEscape").Call(jen.Map(jen.String()).Add(typeCode(m.elem)).Call(jen.Id("v")))))
}

// Public constructors start without a composition context. Request roots also
// validate JSON safety once; children preserve that guard and their caller's
// string context through private parsers without changing the public model.
func emitConstructor(f *jen.File, name string, request bool) {
	f.Func().Id("New"+name).Params(rawParameter()).Params(jen.Id(name), jen.Error()).BlockFunc(func(g *jen.Group) {
		if request {
			g.If(jen.Err().Op(":=").Qual(safePackage, "Validate").Call(jen.Id("raw")), jen.Err().Op("!=").Nil()).Block(jen.Var().Id("zero").Id(name), jen.Return(jen.Id("zero"), jen.Err()))
		}
		g.Return(jen.Id("parse"+name).Call(jen.Id("raw"), jen.False()))
	})
}
