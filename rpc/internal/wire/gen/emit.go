package main

// Emission is deliberately type-directed: schema semantics are resolved and
// rejected by walk before any source is rendered. Generated code contains only
// concrete parsers, not a runtime schema interpreter.
import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type genReport struct {
	nameCollisions                                []collision
	visited                                       map[string]bool
	methods                                       []string
	objects, countFields, countUnions, countShims int
}

type source struct{ strings.Builder }

func (s *source) line(format string, args ...any) { fmt.Fprintf(&s.Builder, format+"\n", args...) }

func emit(reg *registry, version string, roots map[string]*ref, outPath string) error {
	var s source
	reg.report.countUnions = len(reg.unionList)
	reg.report.countShims = 0
	for method, r := range roots {
		if !rootUsesConstructor(method, r) {
			reg.report.countShims++
		}
	}
	s.line("// Code generated by rpc/internal/wire/gen from execution-apis %s; DO NOT EDIT.", version)
	s.line("// Typed official values preserve constraints, declared composition kind and nullable presence.")
	s.line("// Constructors enforce schema constraints. Directly constructed typed values must preserve those invariants;")
	s.line("// marshaling encodes once without revalidation, except for union member selection checks.")
	s.line("// Built from %d methods: %d object types, %d fields, %d unions, %d result shims.", len(reg.report.methods), reg.report.objects, reg.report.countFields, reg.report.countUnions, reg.report.countShims)
	s.line("package wire")
	s.line(`import("encoding/json";"fmt";"regexp";"github.com/codermaybe/ethguard/internal/spec")`)
	s.line("const generatedBundleVersion = %q", version)
	s.line(`func init(){if v:=spec.Version();v!=generatedBundleVersion{panic(fmt.Sprintf("wire: generated spec %%q != pin %%q",generatedBundleVersion,v))}}`)
	// A fixed table, sorted value walk and deterministic private names make the
	// emitted file reproducible without registering constraints during emission.
	for _, n := range natives {
		emitNative(&s, n)
	}
	for _, r := range reg.values {
		emitValue(&s, r)
	}
	for _, obj := range reg.objects {
		emitObject(&s, obj)
	}
	for _, u := range reg.unionList {
		emitUnion(&s, u)
	}
	methods := make([]string, 0, len(roots))
	for method := range roots {
		methods = append(methods, method)
	}
	sort.Strings(methods)
	for _, method := range methods {
		r := roots[method]
		if rootUsesConstructor(method, r) {
			continue
		}
		s.line("// %s parses the complete official %s result.", methodShimName(method), method)
		s.line("func %s(raw json.RawMessage)(%s,error){return %s(raw)}", methodShimName(method), r.displayName(), r.parser)
	}
	data, err := format.Source([]byte(s.String()))
	if err != nil {
		return fmt.Errorf("emit: format: %w", err)
	}
	return os.WriteFile(outPath, data, 0o644)
}

func rootUsesConstructor(method string, r *ref) bool {
	return !r.pointer && (r.kind == refObject || r.kind == refUnion) && methodShimName(method) == "New"+r.typeName
}

func emitNative(s *source, n nativeDescriptor) {
	s.line("// %s is the %s.", n.name, n.doc)
	s.line("type %s string", n.name)
	if n.pattern != "" {
		s.line("var native%sPattern = regexp.MustCompile(%q)", n.name, n.pattern)
	}
	s.line("func New%s(raw json.RawMessage)(%s,error){", n.name, n.name)
	s.line(`if len(raw)==0||IsJSONNull(raw){return "",fmt.Errorf("%s: expected a non-null value")}`, n.name)
	if n.parse.fn != "" {
		s.line("text,err:=%s(raw%s)", n.parse.fn, nativeExtraArgs(n.parse))
		s.line(`if err!=nil{return "",err}`)
		if n.parse.number {
			s.line("return %s(text.String()),nil}", n.name)
		} else {
			if n.pattern != "" {
				s.line(`if !native%sPattern.MatchString(text){return "",fmt.Errorf("%s: canonical spelling %%q does not match official pattern",text)}`, n.name, n.name)
			}
			s.line("return %s(text),nil}", n.name)
		}
	} else {
		s.line(`var text string;if err:=json.Unmarshal(raw,&text);err!=nil{return "",fmt.Errorf("expected string: %%w",err)}`)
		if n.pattern != "" {
			s.line(`if !native%sPattern.MatchString(text){return "",fmt.Errorf("%s: invalid spelling %%q",text)}`, n.name, n.name)
		}
		s.line("return %s(text),nil}", n.name)
	}
	s.line("func(v %s)MarshalJSON()([]byte,error){", n.name)
	if n.parse.number {
		s.line("return []byte(v),nil}")
	} else {
		s.line("return MarshalNoEscape(string(v))}")
	}
}
func nativeExtraArgs(info nativeParseInfo) string {
	var b strings.Builder
	for _, v := range info.extraArgs {
		switch v := v.(type) {
		case string:
			fmt.Fprintf(&b, ",%q", v)
		default:
			fmt.Fprintf(&b, ",%v", v)
		}
	}
	return b.String()
}

func emitValue(s *source, r *ref) {
	pattern := r.pattern
	if nativeForPattern(pattern) == r.native {
		pattern = ""
	}
	if pattern != "" {
		s.line("var %sPattern = regexp.MustCompile(%q)", r.parser, pattern)
	}
	s.line("func %s(raw json.RawMessage)(%s,error){", r.parser, r.displayName())
	if r.pointer {
		s.line("if IsJSONNull(raw){return nil,nil}")
		s.line("value,err:=%s(raw);if err!=nil{return nil,err};return &value,nil}", r.inner.parser)
		return
	}
	s.line("var out %s", r.displayName())
	if r.kind != refUnion {
		s.line(`if len(raw)==0||IsJSONNull(raw){return out,fmt.Errorf(%q)}`, r.path+": expected a non-null value")
	}
	switch r.kind {
	case refScalar:
		if r.native == "bool" || r.native == "int" {
			s.line("if err:=json.Unmarshal(raw,&out);err!=nil{return out,fmt.Errorf(%q,err)}", r.path+": %w")
		} else {
			s.line("value,err:=New%s(raw);if err!=nil{return out,fmt.Errorf(%q,err)};out=value", r.native, r.path+": %w")
		}
	case refObject, refUnion:
		s.line("value,err:=New%s(raw);if err!=nil{return out,err};out=value", r.typeName)
	case refArray:
		s.line("var rows []json.RawMessage;if err:=json.Unmarshal(raw,&rows);err!=nil{return out,fmt.Errorf(%q,err)}", r.path+": expected array: %w")
		s.line("out=make(%s,len(rows));for i,row:=range rows{value,err:=%s(row);if err!=nil{return out,fmt.Errorf(%q,i,err)};out[i]=value}", r.codeName(), r.elem.parser, r.path+"[%d]: %w")
	}
	if r.hasConst {
		if r.native == "Number" {
			s.line("if CompareNumbers(json.Number(out),json.Number(%q))!=0{return out,fmt.Errorf(%q)}", fmt.Sprint(r.constant), r.path+": expected constant")
		} else {
			s.line("if out != %s{return out,fmt.Errorf(%q)}", goLiteral(r.constant), r.path+": expected constant")
		}
	}
	if pattern != "" {
		s.line("if !%sPattern.MatchString(string(out)){return out,fmt.Errorf(%q)}", r.parser, r.path+": does not match official pattern")
	}
	if r.minimum != nil {
		s.line("if CompareNumbers(json.Number(out),json.Number(%q))<0{return out,fmt.Errorf(%q)}", r.minimum.String(), r.path+": below official minimum")
	}
	if r.maximum != nil {
		s.line("if CompareNumbers(json.Number(out),json.Number(%q))>0{return out,fmt.Errorf(%q)}", r.maximum.String(), r.path+": above official maximum")
	}
	s.line("return out,nil}")
}
func goLiteral(v any) string {
	switch v := v.(type) {
	case string:
		return fmt.Sprintf("%q", v)
	default:
		return fmt.Sprintf("%v", v)
	}
}

func fieldType(f fieldModel) string {
	if !f.req {
		return "*" + f.ref.displayName()
	}
	return f.ref.displayName()
}
func fieldTag(f fieldModel) string {
	if !f.req {
		return f.json + ",omitempty"
	}
	return f.json
}
func emitFields(s *source, obj *objectModel) {
	for _, field := range obj.fields {
		s.line("%s %s `json:%q`", field.goName, fieldType(field), fieldTag(field))
	}
}
func emitObject(s *source, obj *objectModel) {
	s.line("// %s is the official execution-apis object; optional nullable fields distinguish absence from null.", obj.name)
	s.line("// New%s enforces schema constraints; directly constructed values must preserve those invariants.", obj.name)
	if len(obj.from) > 1 {
		s.line("// Shape shared by: %s.", strings.Join(obj.from, ", "))
	}
	s.line("type %s struct{", obj.name)
	emitFields(s, obj)
	s.line("}")
	s.line("func New%s(raw json.RawMessage)(%s,error){var out %s", obj.name, obj.name, obj.name)
	s.line(`if len(raw)==0||IsJSONNull(raw){return out,fmt.Errorf(%q)}`, obj.name+": expected a non-null object")
	s.line("var fields struct{")
	for _, field := range obj.fields {
		s.line("%s json.RawMessage `json:%q`", field.goName, field.json)
	}
	s.line("};if err:=json.Unmarshal(raw,&fields);err!=nil{return out,fmt.Errorf(%q,err)}", obj.name+": expected object: %w")
	for _, field := range obj.fields {
		s.line("if len(fields.%s)==0{", field.goName)
		if field.req {
			s.line("return out,fmt.Errorf(%q)", obj.name+": missing required field "+field.json)
		}
		s.line("}else{value,err:=%s(fields.%s);if err!=nil{return out,err}", field.ref.parser, field.goName)
		if field.req {
			s.line("out.%s=value}", field.goName)
		} else {
			s.line("out.%s=&value}", field.goName)
		}
	}
	s.line("return out,nil}")
	s.line("func(v %s)MarshalJSON()([]byte,error){", obj.name)
	// The anonymous struct avoids recursively calling this object's method.
	s.line("return MarshalNoEscape(struct{")
	emitFields(s, obj)
	s.line("}{")
	for _, field := range obj.fields {
		s.line("%s:v.%s,", field.goName, field.goName)
	}
	s.line("})}")
}

func emitUnion(s *source, u *unionModel) {
	s.line("// %s retains the official %s branches in declaration order.", u.name, u.kind)
	if u.kind == "anyOf" {
		s.line("// Multiple matching schemas are valid; the first successful branch is the canonical representation.")
	} else {
		s.line("// Exactly one complete branch must validate.")
	}
	if len(u.from) > 1 {
		s.line("// Shape shared by: %s.", strings.Join(u.from, ", "))
	}
	s.line("type %s struct{", u.name)
	for _, b := range u.branches {
		s.line("// Official %s[%d]: %s.", u.kind, b.index, b.title)
		s.line("%s *%s `json:\"-\"`", b.goName, b.ref.displayName())
	}
	s.line("}")
	s.line("func New%s(raw json.RawMessage)(%s,error){var out %s", u.name, u.name, u.name)
	s.line("matches:=0")
	if u.nullable {
		if u.kind == "anyOf" {
			s.line("if IsJSONNull(raw){return out,nil}")
		} else {
			s.line("if IsJSONNull(raw){matches++}")
		}
	}
	for _, b := range u.branches {
		s.line("if value,err:=%s(raw);err==nil{", b.ref.parser)
		if u.kind == "anyOf" {
			s.line("out.%s=&value;return out,nil", b.goName)
		} else {
			s.line("matches++;out.%s=&value", b.goName)
		}
		s.line("}")
	}
	s.line("if matches!=1{return %s{},fmt.Errorf(%q,matches)};return out,nil}", u.name, u.name+": expected "+u.kind+" branch match, got %d")
	s.line("func(u %s)MarshalJSON()([]byte,error){selected:=0", u.name)
	for _, b := range u.branches {
		s.line("if u.%s!=nil{selected++}", b.goName)
	}
	if u.nullable {
		s.line(`if selected==0{return []byte("null"),nil}`)
	}
	s.line("if selected!=1{return nil,fmt.Errorf(%q,selected)}", u.name+": expected exactly one selected member, got %d")
	for i, b := range u.branches {
		if i < len(u.branches)-1 {
			s.line("if u.%s!=nil{", b.goName)
		}
		if b.ref.pointer || b.ref.kind == refScalar || b.ref.kind == refArray {
			s.line("return MarshalNoEscape(*u.%s)", b.goName)
		} else {
			s.line("return u.%s.MarshalJSON()", b.goName)
		}
		if i < len(u.branches)-1 {
			s.line("}")
		}
	}
	s.line("}")
}

func methodShimName(method string) string { return "New" + methodCamel(method) + "Result" }
func methodCamel(method string) string {
	trimmed := strings.TrimPrefix(method, "eth_")
	trimmed = strings.TrimPrefix(trimmed, "net_")
	if trimmed == "" {
		trimmed = method
	}
	return strings.ToUpper(trimmed[:1]) + trimmed[1:]
}
