package methods

import "testing"

// TestBlockTransactionCountByNumberDefinition pins the method's self-contained definition: the
// file owns the RPC spelling, the spec and the descriptor agree on it, the
// declared reference and pending shape compile, and the spec compiles into
// the plan the registry installs.
func TestBlockTransactionCountByNumberDefinition(t *testing.T) {
	spec := blockTransactionCountByNumberSpec()
	descriptor := blockTransactionCountByNumberDescriptor()
	if spec.Method != MethodGetBlockTransactionCountByNumber || descriptor.Name != spec.Method {
		t.Fatalf("method identity is not self-contained: spec=%+v descriptor=%+v", spec, descriptor)
	}
	if spec.Normalize == nil {
		t.Fatalf("method definition is incomplete: %+v", spec)
	}
	if descriptor.Adapter != "PendingTransactionCount" {
		t.Fatalf("adapter mapping drifted: %+v", descriptor)
	}
	if _, err := CompilePlan(spec); err != nil {
		t.Fatal(err)
	}
}
